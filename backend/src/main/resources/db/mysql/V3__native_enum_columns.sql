-- Hibernate 6 maps @Enumerated(EnumType.STRING) to native MySQL ENUM columns.
-- Keeping the database values constrained also prevents invalid lifecycle states.
ALTER TABLE complaints
    MODIFY COLUMN category ENUM('MISSING_ITEM','WRONG_ITEM','DAMAGED_ITEM','LATE_DELIVERY','OTHER') NOT NULL,
    MODIFY COLUMN status ENUM('OPEN','REVIEWING','RESOLVED','REJECTED') NOT NULL,
    MODIFY COLUMN refund_status ENUM('NONE','PENDING','COMPLETED','REJECTED') NOT NULL;

ALTER TABLE delivery_assignments
    MODIFY COLUMN status ENUM('ASSIGNED','DELIVERING','DELIVERED','FAILED','CANCELLED') NOT NULL,
    MODIFY COLUMN completion_source ENUM('CUSTOMER','RESTAURANT_OVERRIDE');

ALTER TABLE orders
    MODIFY COLUMN cancellation_actor ENUM('CUSTOMER','RESTAURANT','ADMIN','SYSTEM'),
    MODIFY COLUMN cancellation_reason_code ENUM(
        'CUSTOMER_ORDERED_BY_MISTAKE',
        'CUSTOMER_WRONG_ADDRESS',
        'CUSTOMER_CHANGED_MIND',
        'CUSTOMER_WAIT_TOO_LONG',
        'RESTAURANT_OUT_OF_STOCK',
        'RESTAURANT_OVERLOADED',
        'RESTAURANT_CLOSED',
        'RESTAURANT_CANNOT_DELIVER',
        'PAYMENT_EXPIRED',
        'OTHER'
    ),
    MODIFY COLUMN status ENUM('PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED') NOT NULL;

ALTER TABLE order_status_history
    MODIFY COLUMN from_status ENUM('PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED'),
    MODIFY COLUMN to_status ENUM('PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED') NOT NULL;

ALTER TABLE product_option_groups
    MODIFY COLUMN selection_type ENUM('SINGLE','MULTIPLE') NOT NULL;

ALTER TABLE restaurants
    MODIFY COLUMN admin_status ENUM('PENDING','ACTIVE','SUSPENDED','CLOSED') NOT NULL DEFAULT 'ACTIVE';

ALTER TABLE substitution_proposals
    MODIFY COLUMN status ENUM('PENDING_CUSTOMER','ACCEPTED','REJECTED','EXPIRED','CANCELLED') NOT NULL;

ALTER TABLE support_tickets
    MODIFY COLUMN target ENUM('RESTAURANT','ADMIN') NOT NULL,
    MODIFY COLUMN status ENUM('OPEN','IN_PROGRESS','RESOLVED') NOT NULL,
    MODIFY COLUMN priority ENUM('LOW','NORMAL','HIGH','URGENT') NOT NULL DEFAULT 'NORMAL',
    MODIFY COLUMN department ENUM('CUSTOMER_SERVICE','OPERATIONS','FINANCE') NOT NULL DEFAULT 'CUSTOMER_SERVICE';

ALTER TABLE vouchers
    MODIFY COLUMN discount_type ENUM('PERCENT','FIXED') NOT NULL;

ALTER TABLE voucher_redemptions
    MODIFY COLUMN status ENUM('RESERVED','RELEASED') NOT NULL;
