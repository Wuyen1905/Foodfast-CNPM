CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(60) NOT NULL,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    actor_id VARCHAR(100),
    actor_role VARCHAR(24) NOT NULL,
    source VARCHAR(40) NOT NULL,
    reason VARCHAR(500),
    created_at BIGINT NOT NULL,
    CONSTRAINT fk_order_status_history_order FOREIGN KEY (order_id) REFERENCES orders(id)
);

CREATE INDEX idx_order_status_history_order_created
    ON order_status_history(order_id, created_at);

-- Existing orders predate the audit table. Preserve their current state as a
-- migration baseline instead of showing an empty history in the web UI.
INSERT INTO order_status_history (
    order_id, from_status, to_status, actor_id, actor_role, source, reason, created_at
)
SELECT
    id, NULL, status, NULL, 'SYSTEM', 'MIGRATION',
    'Khởi tạo lịch sử từ trạng thái hiện tại',
    CAST(EXTRACT(EPOCH FROM updated_at) * 1000 AS BIGINT)
FROM orders;

CREATE TABLE customer_notifications (
    id VARCHAR(50) PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL,
    order_id VARCHAR(60),
    type VARCHAR(40) NOT NULL,
    title VARCHAR(180) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    action_url VARCHAR(255),
    is_read BOOLEAN NOT NULL,
    created_at BIGINT NOT NULL,
    CONSTRAINT fk_customer_notification_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_customer_notification_order FOREIGN KEY (order_id) REFERENCES orders(id)
);

CREATE INDEX idx_customer_notification_user_created
    ON customer_notifications(user_id, created_at);
