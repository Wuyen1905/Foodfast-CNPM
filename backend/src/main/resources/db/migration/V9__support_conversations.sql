ALTER TABLE support_tickets ADD COLUMN customer_id VARCHAR(50);
ALTER TABLE support_tickets ADD COLUMN customer_name VARCHAR(150);

CREATE INDEX idx_support_tickets_customer ON support_tickets(customer_id, updated_at);

CREATE TABLE support_ticket_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id VARCHAR(50) NOT NULL,
    sender_role VARCHAR(20) NOT NULL,
    sender_id VARCHAR(60) NOT NULL,
    sender_name VARCHAR(150) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    created_at BIGINT NOT NULL,
    CONSTRAINT fk_support_message_ticket FOREIGN KEY (ticket_id) REFERENCES support_tickets(id)
);

CREATE INDEX idx_support_messages_ticket_created
    ON support_ticket_messages(ticket_id, created_at);

