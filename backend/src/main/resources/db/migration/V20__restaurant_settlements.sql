CREATE TABLE restaurant_settlements (
    id VARCHAR(60) PRIMARY KEY,
    restaurant_id VARCHAR(50) NOT NULL,
    restaurant_name VARCHAR(160) NOT NULL,
    period_start TIMESTAMP WITH TIME ZONE NOT NULL,
    period_end TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL,
    order_count INTEGER DEFAULT 0 NOT NULL,
    food_amount BIGINT DEFAULT 0 NOT NULL,
    restaurant_tax_amount BIGINT DEFAULT 0 NOT NULL,
    restaurant_discount_amount BIGINT DEFAULT 0 NOT NULL,
    platform_discount_amount BIGINT DEFAULT 0 NOT NULL,
    commission_rate_bps INTEGER NOT NULL,
    commission_amount BIGINT DEFAULT 0 NOT NULL,
    refund_amount BIGINT DEFAULT 0 NOT NULL,
    adjustment_amount BIGINT DEFAULT 0 NOT NULL,
    payable_amount BIGINT DEFAULT 0 NOT NULL,
    created_by VARCHAR(60) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_by VARCHAR(60),
    submitted_at TIMESTAMP WITH TIME ZONE,
    paid_by VARCHAR(60),
    paid_at TIMESTAMP WITH TIME ZONE,
    payment_reference VARCHAR(120),
    version BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT fk_settlement_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id)
);

CREATE TABLE restaurant_settlement_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id VARCHAR(60) NOT NULL,
    order_id VARCHAR(60) NOT NULL,
    food_amount BIGINT DEFAULT 0 NOT NULL,
    restaurant_tax_amount BIGINT DEFAULT 0 NOT NULL,
    restaurant_discount_amount BIGINT DEFAULT 0 NOT NULL,
    platform_discount_amount BIGINT DEFAULT 0 NOT NULL,
    commission_amount BIGINT DEFAULT 0 NOT NULL,
    refund_amount BIGINT DEFAULT 0 NOT NULL,
    payable_amount BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT fk_settlement_order_batch FOREIGN KEY (settlement_id) REFERENCES restaurant_settlements(id),
    CONSTRAINT fk_settlement_order_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT uk_settlement_order UNIQUE (order_id)
);

CREATE INDEX idx_settlement_status_created ON restaurant_settlements(status, created_at);
CREATE INDEX idx_settlement_restaurant_period ON restaurant_settlements(restaurant_id, period_start, period_end);
CREATE INDEX idx_settlement_orders_batch ON restaurant_settlement_orders(settlement_id);
